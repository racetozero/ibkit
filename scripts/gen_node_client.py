"""Generate crates/ibkit-node/ts/client_requests.ts from the request table
in crates/ibkit-node/src/lib.rs (the `client_requests!` macro), so the typed
TypeScript methods and the native dispatch cannot drift apart. Run from the
repository root::

    uv run --no-project python scripts/gen_node_client.py
"""

from __future__ import annotations

import re
from pathlib import Path

SOURCE = Path('crates/ibkit-node/src/lib.rs')
OUT = Path('crates/ibkit-node/ts/client_requests.ts')

TYPES: dict[str, str] = {
    'i32': 'number',
    'f64': 'number',
    'bool': 'boolean',
    'String': 'string',
    'Value': 'unknown',
    'Vec<TagValue>': 'T.TagValue[]',
}


def camel(name: str) -> str:
    head, *rest = name.rstrip('_').split('_')
    return head + ''.join(p[:1].upper() + p[1:] for p in rest)


def main() -> None:
    text = SOURCE.read_text()
    block = text[text.index('client_requests! {') :]
    block = block[: block.index('\n}\n')]
    lines = [
        '// Generated by scripts/gen_node_client.py from src/lib.rs. Do not edit.',
        "import type * as T from './types.js';",
        '',
        "/** Every request of IB's `EClient` with its argument order. */",
        'export abstract class ClientRequests {',
        '  protected abstract send(method: string, args: unknown[]): void;',
    ]
    for js, args in re.findall(r'"(\w+)" fn \w+\(([^)]*)\);', block):
        params = []
        names = []
        for arg in filter(None, (a.strip() for a in args.split(','))):
            _, name, ty = re.match(r'(val|ref) (\w+): (.+)', arg).groups()
            ts = TYPES.get(ty, f'Partial<T.{ty}>')
            params.append(f'{camel(name)}: {ts}')
            names.append(camel(name))
        lines.append(f'  {js}({", ".join(params)}): void {{')
        lines.append(f"    this.send('{js}', [{', '.join(names)}]);")
        lines.append('  }')
    lines += ['}', '']
    OUT.write_text('\n'.join(lines))
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
