"""Generate crates/ibkit-tws/src/proto.rs from IB's TWS API .proto files.

The TWS API distribution ships its protobuf schema in `source/proto/`. Those
files are licensed by IB and are not copied into this repository. This script
reads them and writes only the wire interface: one Rust module per message
with a constant per field number and a `FIELDS` table (name, number, type),
used for the generic JSON conversion in `pb.rs`.

A message that is in the current `proto.rs` but no longer in the given
schema (IB removed the fundamentals messages in TWS API 10.52) is kept as it
is, so older servers that still send it keep working.

Usage: uv run scripts/gen_protobuf.py <path to TWS API source/proto>
"""

from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import TypedDict

OUT = Path(__file__).resolve().parent.parent / 'crates/ibkit-tws/src/proto.rs'
KEPT_MODULE = re.compile(
    r'^/// `(\w+)`\n(pub mod \w+ \{.*?\n\}\n)', re.DOTALL | re.MULTILINE
)
MESSAGE = re.compile(r'message\s+(\w+)\s*\{(.*?)\n\}', re.DOTALL)
FIELD = re.compile(
    r'^\s*(optional\s+|repeated\s+)?(map<\s*\w+\s*,\s*\w+\s*>|[\w.]+)\s+(\w+)\s*=\s*(\d+)\s*;',
    re.MULTILINE,
)


class Field(TypedDict):
    label: str
    type: str
    name: str
    number: int


def snake(name: str) -> str:
    s = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name)
    s = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', s)
    return s.lower()


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(
            'usage: gen_protobuf.py <proto dir>; pass the source/proto folder of the TWS API download'
        )
    src = Path(sys.argv[1])
    files = sorted(src.glob('*.proto'))
    if not files:
        sys.exit(
            f'no .proto files in {src}; pass the source/proto folder of the TWS API download'
        )
    messages: dict[str, list[Field]] = {}
    for path in files:
        for name, body in MESSAGE.findall(path.read_text()):
            messages[name] = [
                Field(
                    label=label.strip(),
                    type=ty.replace(' ', ''),
                    name=fname,
                    number=int(num),
                )
                for label, ty, fname, num in FIELD.findall(body)
            ]
    # Modules of messages that the new schema no longer has, kept verbatim.
    kept: dict[str, str] = {}
    if OUT.exists():
        for name, text in KEPT_MODULE.findall(OUT.read_text()):
            if name not in messages:
                kept[name] = text
    scalar = {
        'int32': 'Int32',
        'int64': 'Int64',
        'bool': 'Bool',
        'double': 'Double',
        'string': 'String',
    }
    out = [
        '//! Field numbers of the TWS API protobuf messages (server version 201+).',
        '//!',
        '//! Generated by `scripts/gen_protobuf.py` from the `.proto` files of the',
        '//! TWS API distribution; only names, numbers and types are kept. Do not edit.',
        '',
        '#![allow(dead_code)]',
        '',
        'use crate::pb::Field;',
        '',
    ]
    for name in sorted(messages.keys() | kept.keys()):
        out.append(f'/// `{name}`')
        if name in kept:
            out.append(kept[name])
            continue
        out.append(f'pub mod {snake(name)} {{')
        out.append('    #[allow(unused_imports)]')
        out.append('    use crate::pb::{Field, Kind};')
        for f in messages[name]:
            kind = f'{f["label"]} {f["type"]}'.strip()
            out.append(f'    /// {kind}')
            out.append(
                f'    pub const {snake(f["name"]).upper()}: u32 = {f["number"]};'
            )
        out.append('    pub const FIELDS: &[Field] = &[')
        for f in messages[name]:
            ty = f['type']
            if ty.startswith('map<'):
                kind, msg = 'Map', ''
            elif ty in scalar:
                kind, msg = scalar[ty], ''
            else:
                kind, msg = 'Message', ty.split('.')[-1]
            repeated = 'true' if f['label'] == 'repeated' else 'false'
            out.append(
                f'        Field {{ name: "{f["name"]}", number: {f["number"]}, kind: Kind::{kind}, message: "{msg}", repeated: {repeated} }},'
            )
        out.append('    ];')
        out.append('}')
        out.append('')
    out.append('/// Field table of message `name` (as in the .proto files).')
    out.append("pub fn fields(name: &str) -> Option<&'static [Field]> {")
    out.append('    Some(match name {')
    for name in sorted(messages.keys() | kept.keys()):
        out.append(f'        "{name}" => {snake(name)}::FIELDS,')
    out.append('        _ => return None,')
    out.append('    })')
    out.append('}')
    out.append('')
    OUT.write_text('\n'.join(out))
    print(f'wrote {len(messages)} messages to {OUT}')
    if kept:
        print(
            f'kept {len(kept)} messages missing from {src}: {", ".join(sorted(kept))}'
        )


if __name__ == '__main__':
    main()
